#!/usr/bin/env python3
"""Generate solution/flag_data.h for luckypatcher.

The manifest (chall.yaml) is the single source of truth for the flag. This
script reads that flag and encodes it with the same 32-bit LCG keystream the
binary uses in print_flag(). The seed is the progress value produced by
walking all ten good paths, so the encoded bytes are useless without the
patched gates.

Usage:
    python3 solution/gen_flag.py chall.yaml solution/flag_data.h
"""
import sys

import yaml

# One 32-bit key per gate. The same values are emitted into flag_data.h and
# used by gate_1..gate_10 in luckypatcher.c.
GATE_KEYS = [
    0x9E3779B1,
    0x85EBCA77,
    0xC2B2AE3D,
    0x27D4EB2F,
    0x165667B1,
    0xD3A2646C,
    0xFD7046C5,
    0xB55A4F09,
    0x9E3779B9,
    0x7F4A7C15,
]


def lcg(state: int) -> int:
    return (state * 1664525 + 1013904223) & 0xFFFFFFFF


def encode(flag: bytes, seed: int) -> list[int]:
    state = seed
    out = []
    for ch in flag:
        state = lcg(state)
        key = (state >> 24) & 0xFF
        out.append(ch ^ key)
    return out


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: gen_flag.py <chall.yaml> <flag_data.h>")

    manifest, out_path = sys.argv[1], sys.argv[2]
    with open(manifest) as f:
        manifest_data = yaml.safe_load(f)
    flag = manifest_data["flag"].encode()

    progress = 0
    for key in GATE_KEYS:
        progress = (lcg(progress) + key) & 0xFFFFFFFF

    encoded = encode(flag, progress)

    with open(out_path, "w") as f:
        f.write("/* generated by gen_flag.py from chall.yaml -- do not edit */\n")
        f.write("#ifndef LUCKYPATCHER_FLAG_DATA_H\n")
        f.write("#define LUCKYPATCHER_FLAG_DATA_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define FLAG_LEN {len(flag)}\n\n")
        f.write("static const uint32_t GATE_KEYS[10] = {\n")
        for i in range(0, len(GATE_KEYS), 4):
            row = ", ".join(f"0x{k:08X}u" for k in GATE_KEYS[i:i + 4])
            f.write(f"    {row},\n")
        f.write("};\n\n")
        f.write("static const unsigned char FLAG_ENC[FLAG_LEN] = {\n")
        for i in range(0, len(encoded), 12):
            row = ", ".join(f"0x{b:02X}" for b in encoded[i:i + 12])
            f.write(f"    {row},\n")
        f.write("};\n\n")
        f.write("#endif\n")

    print(f"flag length: {len(flag)}")
    print(f"expected progress: 0x{progress:08X}")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
