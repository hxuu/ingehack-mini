#!/usr/bin/env python3
"""Generate SecretData.kt with encrypted decoys and the real flag."""
from __future__ import annotations

import base64
import hashlib
import os
import re
from pathlib import Path

import yaml
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

ROOT = Path(__file__).resolve().parent
CHALLENGE = ROOT.parent
PKG = ROOT / "app/app/src/main/java/com/ingehack/keepsecrets"
CRYPTO = PKG / "VaultCrypto.kt"


def load_key() -> tuple[str, bytes]:
    source = CRYPTO.read_text()
    first = re.search(r'FIRST\s*=\s*"([^"]+)"', source)
    second = re.search(r'SECOND\s*=\s*"([^"]+)"', source)
    if not first or not second:
        raise SystemExit("could not read FIRST/SECOND from VaultCrypto.kt")
    passphrase = f"{first.group(1)} {second.group(1)}"
    return passphrase, hashlib.sha256(passphrase.encode()).digest()


def seal(key: bytes, plaintext: str) -> str:
    iv = os.urandom(12)
    ciphertext = AESGCM(key).encrypt(iv, plaintext.encode(), None)
    return base64.b64encode(iv + ciphertext).decode()


def main() -> None:
    passphrase, key = load_key()
    flag = yaml.safe_load((CHALLENGE / "chall.yaml").read_text())["flag"]
    entries = [
        ("Ashford", "The student council room is safe. For now."),
        ("Nunnally", "I will build a gentler world for her."),
        ("Black Knights", "The next operation begins at midnight."),
        ("???", flag),
        ("C.C.", "She still owes me a pizza."),
    ]

    lines = [
        "package com.ingehack.keepsecrets",
        "",
        "// Generated by solution/gen_secrets.py. Ciphertext only; the flag itself",
        "// is kept in chall.yaml and is never written into the APK in plaintext.",
        "object SecretData {",
        "    val BAKED_SECRETS = listOf(",
    ]
    for title, plaintext in entries:
        lines.append(f'        VaultEntry("{title}", "{seal(key, plaintext)}"),')
    lines += ["    )", "}", ""]

    output = PKG / "SecretData.kt"
    output.write_text("\n".join(lines))
    print(f"wrote {output}")
    print(f"key passphrase: {passphrase!r}")
    print(f"entries: {len(entries)}")


if __name__ == "__main__":
    main()
